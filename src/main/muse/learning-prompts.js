'use strict'

// 学习图谱「活的书」提示词：章节撰写 / 圈选提问 / 下钻衍生 / 验收出题 / 批改引导，
// 以及三层模型里的骨架铺开、横向平铺、跨域门户。
// muse-handlers（交互式）与 learning-prefetch（后台预生成）共用，保证两条链路产出风格一致。

function buildLearningPrompt({
  kind, mapTitle, nodePath, nodeTitle, selection, question, content, answers, nodeDirectory,
  description, existingTitles, siblingTitles, outlineTitles,
}) {
  const context = `知识图谱：${mapTitle || ''}\n章节路径：${nodePath || nodeTitle}\n当前节点：${nodeTitle}`
  // skeleton：给整个领域铺一份清单，作为「分母」。这是全局感的唯一来源，
  // 因为个人探索永远长不出「你不知道自己不知道」的部分。
  //
  // 这份提示词决定了下限：骨架不完整，后面所有的覆盖度与色块都只是比例尺错的仪表盘。
  // 因此它不只要「列出一些知识点」，而要被一份覆盖维度清单逼着交出完整结构。
  if (kind === 'skeleton') {
    return [
      '你正在为一位自学者铺出某个领域的知识骨架。骨架的作用是给出「分母」：让他知道这个领域到底包含什么、自己走到哪了，而不是替他学习。',
      '',
      `领域：${mapTitle || ''}`,
      description ? `学习目标：${description}` : '',
      existingTitles ? `以下知识点已经存在，不要重复列出：\n${existingTitles}` : '',
      '',
      '覆盖要求 —— 一个领域的骨架至少要回答下面八类问题。每一类都必须落到具体的分支或知识点上，不允许只覆盖前面几类就收工：',
      '1. 基础概念与前提：核心定义、术语体系、绕不开的物理或成本约束',
      '2. 核心机制与原理：它到底怎么运作，为什么这样设计',
      '3. 范式与方法谱系：有哪些主要路线，各自的适用场景与代价',
      '4. 工具、协议与实践：实际动手时用到什么，生态里现成的东西有哪些',
      '5. 质量与评估：怎么度量做得好不好，指标怎么来的',
      '6. 风险与失败模式：会怎么坏，怎么防，出了问题怎么定位',
      '7. 边界与争议：哪些是公认结论、哪些只是主流做法、哪些仍有分歧',
      '8. 相邻领域接口：它通向哪些别的领域，接口上的概念是什么',
      '',
      '结构要求：',
      '1. 6-10 个一级分支，每个分支 4-7 个直接子知识点，总计 45-70 个知识点。',
      '2. 一级分支是这个领域的主要板块，彼此边界清晰、不重叠；子知识点是具体可学的概念，不要「概述」「简介」「进阶」「其他」这类套话。',
      '3. 只有当某个子知识点确实有公认的分解方式时，才在它下面再给一层 children。不要为了凑层数而拆——凑出来的层级会让分母虚高，反而破坏全局感。',
      '4. 标题尽量短（12 字以内）。summary 说明这个知识点解决什么问题（40 字以内），不要复述标题。',
      '5. 必须包含初学者不会主动想到、但确实重要的部分——这正是骨架存在的意义。宁可给出让人不舒服的空白板块，也不要只列他肯定会自己发现的那些。',
      '6. 这是首轮骨架，不是最终答案：scaleEstimate 要诚实给出这个领域大致有多少个值得独立学习的概念，即使远大于本次产出的数量也要写真实数字。',
      existingTitles ? '7. 只输出尚不存在的分支与知识点，已经列出的不要重复。' : '',
      '',
      '只输出 JSON，不要任何其他文字或 markdown 围栏：',
      '{"scaleEstimate":该领域大致有多少个值得独立学习的概念(整数),"branches":[{"title":"分支名","summary":"这一支讲什么","children":[{"title":"知识点","summary":"它解决什么问题","children":[{"title":"细分知识点","summary":"它解决什么问题"}]}]}]}',
    ].filter(Boolean).join('\n')
  }
  // spread：横向平铺。读者想知道「同一层还有哪些同类」，而不是继续往下钻。
  // 这是「生态感」的来源，与 drill（纵深）对称。
  if (kind === 'spread') {
    return [
      '读者已经读懂了下面这个知识点，现在想知道「和它同一层还有哪些同类」。注意：不是继续往下钻，而是横向看看这个生态位里还站着谁。',
      '',
      context,
      selection ? `圈选内容：\n${selection}` : '',
      siblingTitles ? `已经存在的同层知识点（不要重复）：\n${siblingTitles}` : '',
      '',
      '要求：',
      '1. 给出 3-5 个与当前知识点同层、平级的同类：可以是替代方案、平行体系、相邻生态位。',
      '2. 必须是真实存在、有公开名称的做法或体系，不要为了凑数编造；每个都要说清它和当前知识点处在同一层级的理由，以及各自适合什么场景。不要给出当前知识点的子概念。',
      '3. 标题短（12 字以内），summary 50 字以内，reason 必须落在事实上（同一抽象层、同一生态位、可互相替代），不要用「都很重要」「各有优劣」这类空话。',
      '',
      '只输出 JSON 数组，不要任何其他文字或 markdown 围栏：',
      '[{"title":"同类知识点短标题","summary":"它是什么、解决什么问题","reason":"为什么它和当前知识点同级"}]',
    ].filter(Boolean).join('\n')
  }
  // portal：跨域门户。找出这个知识点和别的领域接壤的地方，标成「通往外面的门」。
  if (kind === 'portal') {
    return [
      '读者想知道下面这个知识点「通向外面的门」：它和哪些别的领域接壤，那些领域里的哪个概念是它的邻居或支撑。',
      '',
      context,
      selection ? `圈选内容：\n${selection}` : '',
      '',
      '要求：',
      '1. 给出 2-4 个跨领域连接。领域名与对方的概念名都必须是真实存在的学科/技术领域与公认概念，不要生造。',
      '2. concept 写清对方领域里具体是哪个概念（不是领域名本身）；bridge 要说清两者在**哪一层**握手——是共用数据结构、共享协议、借用数学工具，还是复用同一套评估方法。',
      '3. 优先给出「学了它才能看懂当前知识点深层原理」的领域，而不是泛泛相关。',
      '',
      '只输出 JSON 数组，不要任何其他文字或 markdown 围栏：',
      '[{"domain":"领域名","concept":"对方领域里的具体概念","bridge":"两者在哪里握手、如何互相支撑"}]',
    ].filter(Boolean).join('\n')
  }
  if (kind === 'content') {
    return [
      `你正在为一部关于「${mapTitle || '这个主题'}」的领域教材撰写其中一章。读者会按目录顺序系统学习，所以这一章必须像正式教材那样：自足、准确、可查证，并与前后章节分工清楚。`,
      '',
      context,
      outlineTitles ? `全书目录（用来判断本章与邻章的分工，别的章节已经讲透的内容不要重复讲）：\n${outlineTitles}` : '',
      siblingTitles ? `与本章并列的同层章节（读者会连着读，务必与之区分，不要写成同一篇）：\n${siblingTitles}` : '',
      '',
      '写作要求：',
      '1. 结构固定，用三级标题，共四节：### 技术要点（4-6 条核心结论，每条以加粗短语开头）→ ### 深入讲解（讲透机制与原理，重点回答 why）→ ### 实例（见第 6 条）→ ### 常见误区与考点。不要用一级或二级标题重复节点名。',
      '2. 「技术要点」的第一条必须是**可判定的定义**：这个概念是什么、它不是什么、它与最容易被混淆的相邻概念的界线在哪。不要用同义词替换来充当定义。',
      '3. 讲机制要给具体量级：数字、阈值、复杂度、协议字段、数据结构、时间或空间代价。停在「性能更好」「更加灵活」「更加健壮」这类无法验证的说法上，这一章就是失败的。',
      '4. 区分确定性的三个层次：**公认结论** / **主流做法** / **仍有分歧**。存在分歧的地方直接说出来，不要把一家之言写成普遍规律，也不要把工程惯例写成理论结论。',
      '5. 不要编造 API 名称、版本号、论文、标准编号或基准数字。不确定就写明不确定，或者只描述机制而不给具体出处。宁可少一个数字，不可多一条假的。',
      '6. 第三小节按主题类型落地：工程与技术主题用 ### 代码实例（完整可运行、标注语言、关键行加注释）；非工程主题（人文、社科、艺术、历史等）改用 ### 实例与证据，给出真实案例、原始材料片段或可复算的数据，地位与代码实例等同，不允许省略。',
      '7. 正文 900-1800 字（不含代码），信息密度优先。禁止注水：不要排比式总结、不要「总而言之」、不要复述上文。',
      '8. 直接输出正文，不要开场白、不要「以下是」、不要结尾套话。',
    ].filter(Boolean).join('\n')
  }
  if (kind === 'ask') {
    return [
      '读者正在阅读一本技术书的某章节，对圈选的内容有疑问，请像作者当面讲解一样回答。',
      '',
      context,
      '',
      `圈选内容：\n${selection || ''}`,
      '',
      `读者的问题：${question || '解释这段内容'}`,
      '',
      '要求：紧扣圈选片段讲透。先回答「这段的原意在说什么」，再补充背景或延伸；两者要分得开，不要把补充内容说成是原文的观点。超出本段范围的问题，明确说明它属于别处，只回答能确定的部分。必要时补充代码示例或类比；Markdown 格式；直接回答，不要客套话。',
    ].join('\n')
  }
  // quiz：读完章节后的验收出题，考理解与应用，不给答案
  if (kind === 'quiz') {
    return [
      '你是技术书的验收考官。读者刚读完下面这一章，请出 3 道验收题，检验他是否真正理解。',
      '',
      context,
      '',
      `章节内容：\n${String(content || '').slice(0, 6000)}`,
      '',
      '出题要求：',
      '1. 考理解与应用而非背诵：问机制、为什么、权衡取舍；至少一道是场景判断题（给定具体场景让读者判断做法或结果）。',
      '2. 每道题读者可用 1-3 句话作答，题目本身自含必要背景。',
      '3. 不要给出答案或提示。',
      '只输出 JSON 数组，不要任何其他文字或 markdown 围栏：',
      '[{"question":"题目","keyPoint":"考察点（10字以内）"}]',
    ].join('\n')
  }
  // grade：批改验收答案，并根据错题从书目目录中推荐阅读路径
  if (kind === 'grade') {
    return [
      '你是技术书的验收考官。读者读完一章后完成了验收题，请依据章节内容逐题批改，并根据薄弱点给出本书内的阅读引导。',
      '',
      context,
      '',
      `章节内容：\n${String(content || '').slice(0, 6000)}`,
      '',
      `验收题与读者的作答：\n${answers || ''}`,
      '',
      `本书目录（nodeId 与章节名，引导只能从这里选）：\n${nodeDirectory || ''}`,
      '',
      '批改要求：',
      '1. 以章节内容为事实依据逐题判定；方向对但关键机制缺失或不准确的判不通过，comment 必须点出具体缺了什么。',
      '2. guidance：为每道未通过的题从目录推荐 1 个最相关章节；nodeId 必须和目录方括号里的 ID 完全一致，nodeTitle 用同一行的章节名，reason 说明它补的是哪个缺口；全部通过则 guidance 为空数组。',
      '只输出 JSON，不要任何其他文字或 markdown 围栏：',
      '{"results":[{"pass":true,"comment":"一句话点评"}],"guidance":[{"nodeId":"目录中的 ID","nodeTitle":"章节名","reason":"补什么缺口"}]}',
    ].join('\n')
  }
  // drill：基于圈选内容或节点本身衍生子知识点
  return [
    '读者在阅读时想对下面的内容继续下钻深入。请给出 3-5 个值得展开的子知识点。',
    '',
    context,
    selection ? `圈选内容：\n${selection}` : '',
    '',
    '要求：',
    '1. 子知识点必须是这个概念在领域内公认的分解方向，用该领域通行的说法命名；不要生造名词，也不要把「深入理解 X」「X 的更多细节」这类同义反复当成子知识点。',
    '2. 彼此边界清晰、不重叠；如果两项说的其实是一回事，就合并成一项。',
    '3. summary 讲清它解决什么问题、为什么值得单独学（50 字以内），不要只预告「将介绍…」。',
    '',
    '只输出 JSON 数组，不要任何其他文字或 markdown 围栏：',
    '[{"title":"子知识点短标题（12字以内）","summary":"它解决什么问题、为什么值得单独学（50字以内）"}]',
  ].filter(Boolean).join('\n')
}

module.exports = { buildLearningPrompt }
